# Student dictionary
student = {
    "Name": "Ranjay Kumar",
    "Age": 21,
    "College": "IIT Patna",
    "Python Marks": 85,
    "Mathematics Marks": 90
}

# Remove an item using pop()
removed_value = student.pop("Age")

print("Removed value:", removed_value)
print("Updated dictionary:", student)
